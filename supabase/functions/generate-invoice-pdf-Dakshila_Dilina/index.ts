import { serve } from "https://deno.land/std@0.168.0/http/server.ts";
import { createClient } from "https://esm.sh/@supabase/supabase-js@2";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

/**
 * Builds a zero-dependency, 100% valid PDF-1.4 document string
 */
function buildInvoicePdf({
  businessName,
  businessPhone,
  businessAddress,
  orderRef,
  orderDate,
  customerName,
  whatsappPhone,
  normalPhone,
  deliveryAddress,
  district,
  paymentMethod,
  paymentStatus,
  items,
  totalAmount,
}: {
  businessName: string;
  businessPhone: string;
  businessAddress: string;
  orderRef: string;
  orderDate: string;
  customerName: string;
  whatsappPhone: string;
  normalPhone: string;
  deliveryAddress: string;
  district: string;
  paymentMethod: string;
  paymentStatus: string;
  items: Array<{ name: string; size_color?: string; quantity: number; price: number }>;
  totalAmount: number;
}): string {
  function esc(text: string): string {
    return String(text || "")
      .replace(/\\/g, "\\\\")
      .replace(/\(/g, "\\(")
      .replace(/\)/g, "\\)");
  }

  const ops: string[] = [];

  // Header background (Navy Blue #1e3a8a)
  ops.push("0.12 0.23 0.54 rg");
  ops.push("0 720 595 122 re f");

  // Title in Header
  ops.push("1 1 1 rg");
  ops.push(`BT /F2 20 Tf 40 790 Td (${esc(businessName)}) Tj ET`);
  ops.push(`BT /F1 9.5 Tf 40 770 Td (${esc(businessAddress)} | Tel: ${esc(businessPhone)}) Tj ET`);
  ops.push("BT /F1 8.5 Tf 40 755 Td (Official Sales Invoice & Delivery Confirmation Document) Tj ET");

  ops.push("BT /F2 15 Tf 410 790 Td (CUSTOMER INVOICE) Tj ET");
  ops.push(`BT /F2 9.5 Tf 410 770 Td (Ref: ${esc(orderRef)}) Tj ET`);
  ops.push(`BT /F1 9 Tf 410 755 Td (Date: ${esc(orderDate)}) Tj ET`);

  // Customer & Delivery Box
  ops.push("0.96 0.97 0.99 rg 40 615 515 90 re f");
  ops.push("0.85 0.88 0.93 RG 1 w 40 615 515 90 re s");

  ops.push("0.2 0.3 0.5 rg");
  ops.push("BT /F2 10 Tf 50 688 Td (CUSTOMER & DELIVERY INFORMATION) Tj ET");

  ops.push("0.1 0.1 0.1 rg");
  ops.push(`BT /F2 11 Tf 50 670 Td (Name: ${esc(customerName)}) Tj ET`);
  ops.push(`BT /F1 9.5 Tf 50 652 Td (WhatsApp: ${esc(whatsappPhone)}  |  Alt Contact: ${esc(normalPhone)}) Tj ET`);
  ops.push(`BT /F1 9.5 Tf 50 635 Td (Delivery Address: ${esc(deliveryAddress)}${district ? ` [District: ${esc(district)}]` : ""}) Tj ET`);
  ops.push(`BT /F2 9 Tf 50 620 Td (Payment Method: ${esc(paymentMethod)}  |  Status: ${esc(paymentStatus.toUpperCase())}) Tj ET`);

  // Items Header Table
  let y = 575;
  ops.push("0.18 0.28 0.48 rg 40 570 515 24 re f");
  ops.push("1 1 1 rg");
  ops.push(`BT /F2 9.5 Tf 50 ${y + 2} Td (Item Description) Tj ET`);
  ops.push(`BT /F2 9.5 Tf 330 ${y + 2} Td (Qty) Tj ET`);
  ops.push(`BT /F2 9.5 Tf 390 ${y + 2} Td (Unit Price) Tj ET`);
  ops.push(`BT /F2 9.5 Tf 480 ${y + 2} Td (Total) Tj ET`);

  y -= 25;
  ops.push("0.15 0.15 0.15 rg");

  const safeItems = items.length > 0 ? items : [{ name: "Product Order", quantity: 1, price: totalAmount }];
  for (const it of safeItems) {
    const itemDesc = it.size_color ? `${it.name} (${it.size_color})` : it.name;
    const qty = Number(it.quantity || 1);
    const price = Number(it.price || 0);
    const rowTotal = qty * price;

    ops.push(`BT /F1 9 Tf 50 ${y + 4} Td (${esc(itemDesc.substring(0, 42))}) Tj ET`);
    ops.push(`BT /F1 9 Tf 335 ${y + 4} Td (${qty}) Tj ET`);
    ops.push(`BT /F1 9 Tf 390 ${y + 4} Td (LKR ${price.toLocaleString()}) Tj ET`);
    ops.push(`BT /F1 9 Tf 480 ${y + 4} Td (LKR ${rowTotal.toLocaleString()}) Tj ET`);

    // Divider line
    ops.push(`0.88 0.90 0.93 RG 0.5 w 40 ${y - 2} m 555 ${y - 2} l S`);
    y -= 24;
  }

  // Total Box
  y -= 15;
  ops.push(`0.95 0.98 0.95 rg 340 ${y - 10} 215 36 re f`);
  ops.push(`0.15 0.60 0.25 RG 1.2 w 340 ${y - 10} 215 36 re s`);
  ops.push("0.10 0.50 0.20 rg");
  ops.push(`BT /F2 11 Tf 355 ${y + 9} Td (TOTAL AMOUNT:) Tj ET`);
  ops.push(`BT /F2 12.5 Tf 450 ${y + 9} Td (LKR ${totalAmount.toLocaleString()}) Tj ET`);

  // Footer & Logistics notes
  ops.push("0.4 0.4 0.4 rg");
  ops.push("BT /F1 9 Tf 40 75 Td (Thank you for shopping with us! For order assistance, reply directly on WhatsApp.) Tj ET");
  ops.push("BT /F1 8 Tf 40 60 Td (Official Customer Invoice generated by BuildStart Sales Platform for Dakshila & Dilina Store.) Tj ET");

  const streamBody = ops.join("\n");
  const encoder = new TextEncoder();
  const streamLen = encoder.encode(streamBody).length;

  const objects: string[] = [];
  objects[1] = "<< /Type /Catalog /Pages 2 0 R >>";
  objects[2] = "<< /Type /Pages /Kids [3 0 R] /Count 1 >>";
  objects[3] = "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>";
  objects[4] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>";
  objects[5] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>";
  objects[6] = `<< /Length ${streamLen} >>\nstream\n${streamBody}\nendstream`;

  let out = "%PDF-1.4\n";
  const xref: number[] = [0];
  for (let i = 1; i <= 6; i++) {
    xref[i] = encoder.encode(out).length;
    out += `${i} 0 obj\n${objects[i]}\nendobj\n`;
  }
  const startXref = encoder.encode(out).length;
  out += "xref\n0 7\n0000000000 65535 f \n";
  for (let i = 1; i <= 6; i++) {
    out += `${String(xref[i]).padStart(10, "0")} 00000 n \n`;
  }
  out += `trailer\n<< /Size 7 /Root 1 0 R >>\nstartxref\n${startXref}\n%%EOF\n`;
  return out;
}

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response("ok", { headers: corsHeaders });
  }

  try {
    const supabaseUrl = Deno.env.get("SUPABASE_URL")!;
    const supabaseServiceKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
    const supabase = createClient(supabaseUrl, supabaseServiceKey, {
      db: { schema: "Dakshila_Dilina" },
    });

    const { orderId, userId, sessionApiKey } = await req.json();

    if (!orderId) {
      return new Response(JSON.stringify({ error: "Missing orderId" }), {
        status: 400,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    console.log(`[generate-invoice-pdf] Generating invoice for Order ${orderId}`);

    // Fetch order details
    const { data: order, error: orderError } = await supabase
      .from("orders")
      .select("*")
      .eq("id", orderId)
      .single();

    if (orderError || !order) {
      throw new Error(`Order not found: ${orderError?.message || orderId}`);
    }

    const effectiveUserId = userId || order.user_id;

    // Fetch business profile / settings
    const { data: settingsData } = await supabase
      .from("settings")
      .select("key, value")
      .eq("user_id", effectiveUserId);

    const invoiceSettings = settingsData?.find((s: any) => s.key === "invoice_settings")?.value || {};
    const businessName = invoiceSettings.business_name || "Dakshila & Dilina Store";
    const businessPhone = invoiceSettings.business_phone || "0784189365";
    const businessAddress = invoiceSettings.business_address || "Colombo, Sri Lanka";

    const orderRef = `BS-ORD-${order.id.substring(0, 8).toUpperCase()}`;
    const orderDate = new Date(order.created_at || Date.now()).toLocaleDateString("en-GB", {
      year: "numeric",
      month: "short",
      day: "numeric",
    });

    const items = Array.isArray(order.order_items) ? order.order_items : [];

    // Generate PDF string
    const pdfString = buildInvoicePdf({
      businessName,
      businessPhone,
      businessAddress,
      orderRef,
      orderDate,
      customerName: order.customer_name || "Valued Customer",
      whatsappPhone: order.whatsapp_phone || order.customer_phone || "",
      normalPhone: order.normal_phone || order.customer_phone || "",
      deliveryAddress: order.customer_address || "Delivery Address",
      district: order.district || "",
      paymentMethod: order.payment_method === "cod" ? "Cash on Delivery (COD)" : "Bank Transfer",
      paymentStatus: order.payment_status || "Pending",
      items,
      totalAmount: Number(order.total_amount || 0),
    });

    // Base64 encode for reliable WhatsApp attachment and data URI storage
    const encoder = new TextEncoder();
    const pdfBytes = encoder.encode(pdfString);
    let binary = "";
    const len = pdfBytes.byteLength;
    for (let i = 0; i < len; i++) {
      binary += String.fromCharCode(pdfBytes[i]);
    }
    const base64PdfDataUri = `data:application/pdf;base64,${btoa(binary)}`;

    // Also attempt uploading to Supabase Storage if bucket exists
    let publicPdfUrl = base64PdfDataUri;
    try {
      const fileName = `${orderRef}.pdf`;
      const { error: uploadError } = await supabase.storage
        .from("invoices")
        .upload(fileName, pdfBytes, {
          contentType: "application/pdf",
          upsert: true,
        });

      if (!uploadError) {
        const { data: urlData } = supabase.storage.from("invoices").getPublicUrl(fileName);
        if (urlData?.publicUrl) {
          publicPdfUrl = urlData.publicUrl;
        }
      }
    } catch (stErr) {
      console.warn("[generate-invoice-pdf] Storage bucket upload notice:", stErr);
    }

    // Save URL to order record
    await supabase.from("orders").update({
      bill_pdf_url: publicPdfUrl,
      updated_at: new Date().toISOString(),
    }).eq("id", orderId);

    // Resolve active WAHA session name
    let effectiveSession = sessionApiKey;
    if (!effectiveSession || effectiveSession === "jjjc" || effectiveSession === "huyt" || effectiveSession === "hloe") {
      const { data: sessRow } = await supabase
        .from("user_wsender_sessions")
        .select("session_name, session_id, session_api_key")
        .eq("user_id", effectiveUserId)
        .order("created_at", { ascending: false })
        .limit(1)
        .maybeSingle();
      effectiveSession = sessRow?.session_name || sessRow?.session_id || sessRow?.session_api_key || "hawre";
    }

    // Dispatch PDF to customer via WhatsApp document message
    const customerPhone = order.whatsapp_phone || order.customer_phone;
    if (customerPhone) {
      const sendCaption = `📄 Here is your official invoice for Order #${orderRef}. Thank you for shopping with us!`;

      console.log(`[generate-invoice-pdf] Sending invoice document to ${customerPhone} via WAHA session ${effectiveSession}...`);
      try {
        const sendRes = await fetch(`${supabaseUrl}/functions/v1/send-whatsapp-Dakshila_Dilina`, {
          method: "POST",
          headers: {
            Authorization: `Bearer ${supabaseServiceKey}`,
            "Content-Type": "application/json",
          },
          body: JSON.stringify({
            to: customerPhone,
            message: sendCaption,
            mediaUrl: base64PdfDataUri,
            filename: `Bill_${orderRef}.pdf`,
            mediaType: "document",
            sessionApiKey: effectiveSession,
          }),
        });

        if (!sendRes.ok) {
          const errText = await sendRes.text();
          console.error(`[generate-invoice-pdf] WhatsApp dispatch error (${sendRes.status}):`, errText);
        } else {
          console.log(`[generate-invoice-pdf] WhatsApp invoice document successfully sent to ${customerPhone}`);
        }

        // Store outbound document message in conversations table
        await supabase.from("conversations").insert({
          phone_number: customerPhone,
          message: sendCaption,
          direction: "outbound",
          message_type: "document",
          metadata: {
            document_url: publicPdfUrl,
            filename: `Bill_${orderRef}.pdf`,
            order_id: order.id,
            order_ref: orderRef,
          },
          user_id: effectiveUserId,
        });
      } catch (sendErr: any) {
        console.error("[generate-invoice-pdf] WhatsApp dispatch exception:", sendErr?.message || sendErr);
      }
    }

    return new Response(
      JSON.stringify({ success: true, pdfUrl: publicPdfUrl, orderRef }),
      { status: 200, headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  } catch (error) {
    console.error("[generate-invoice-pdf] Error:", error);
    return new Response(
      JSON.stringify({ error: (error as Error).message }),
      { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  }
});
